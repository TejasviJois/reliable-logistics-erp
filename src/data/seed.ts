function boxes(docketId: string, count: number, scanned: number): Docket["boxes"] {
  return Array.from({ length: count }, (_, i) => {
    const n = i + 1;
    const isScanned = n <= scanned;
    return {
      id: `${docketId}-box-${n}`,
      barcode: `${docketId.replace("dk-", "BX-")}-${String(n).padStart(2, "0")}`,
      scanned: isScanned,
      scannedAt: isScanned ? "2026-09-17T09:12:00+05:30" : undefined,
      status: isScanned ? ("staged" as const) : ("pending" as const),
    };
  });
}

