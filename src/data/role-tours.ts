import type { DemoRole } from "@/data/demo-users";

export type TourStep = {
  route: string;
  /** CSS selector — prefer [data-tour="…"] */
  target: string;
  title: string;
  body: string;
  chapter?: string;
  /** click target before wait; wait for target after nav/open */
  action?: "none" | "click" | "clickThenWait";
  /** Selector to click when action is click / clickThenWait (defaults to target) */
  clickTarget?: string;
  /** Selector that must appear after click (spotlight when clickThenWait) */
  waitFor?: string;
  /** Click these first (tabs etc.) before measuring the target */
  prepare?: string[];
  placement?: "bottom" | "top" | "left" | "right";
};

export type RoleTour = {
  role: DemoRole;
  title: string;
  steps: TourStep[];
  nextRole: {
    role: DemoRole;
    label: string;
    artifact: string;
    howTogether: string;
  } | null;
};

export function tourFor(role: DemoRole) {
  return ROLE_TOURS.find((t) => t.role === role);
}

export function tourChapters(tour: RoleTour): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const s of tour.steps) {
    if (s.chapter && !seen.has(s.chapter)) {
      seen.add(s.chapter);
      out.push(s.chapter);
    }
  }
  return out;
}

